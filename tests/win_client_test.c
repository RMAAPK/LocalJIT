#include <windows.h>
#include <wininet.h>
#include <stdio.h>
#include <stdint.h>

#pragma comment(lib, "wininet.lib")

// Windows Test Application for Local JIT
// - Demonstrates Windows PE execution with dynamic JIT page allocation (VirtualAlloc PAGE_EXECUTE_READWRITE)
// - Executes ARM64 micro-ops translated to native x86 machine code
// - Queries the Local JIT vault server

typedef uint64_t (*JitFunction)(uint64_t* regs);

int main() {
    printf("========================================================\n");
    printf("  Windows Native PE Client running via Local JIT Bridge\n");
    printf("  Architecture: x86_64 PE (System: Windows / Wine ABI)\n");
    printf("========================================================\n\n");

    // 1. Allocate executable memory page via Windows VirtualAlloc
    printf("[+] Step 1: Allocating Windows executable memory (PAGE_EXECUTE_READWRITE)...\n");
    void* exec_mem = VirtualAlloc(
        NULL,
        4096,
        MEM_COMMIT | MEM_RESERVE,
        PAGE_EXECUTE_READWRITE
    );

    if (!exec_mem) {
        printf("[-] Failed to allocate memory: %lu\n", GetLastError());
        return 1;
    }
    printf("[+] Executable page mapped at: 0x%p\n", exec_mem);

    // 2. Machine code generated by Local JIT:
    // mov (%rcx), %rax       ; rcx = registers pointer in Windows x64 ABI
    // add $42, %rax          ; add immediate
    // mov %rax, (%rcx)       ; store back to registers[0]
    // ret
    uint8_t win_x86_code[] = {
        0x48, 0x8B, 0x01,                   // mov (%rcx), %rax
        0x48, 0x05, 0x2A, 0x00, 0x00, 0x00, // add $42, %rax
        0x48, 0x89, 0x01,                   // mov %rax, (%rcx)
        0xC3                                // ret
    };

    printf("[+] Step 2: Injecting translated JIT machine code (11 bytes)...\n");
    memcpy(exec_mem, win_x86_code, sizeof(win_x86_code));

    // 3. Execute
    printf("[+] Step 3: Invoking JIT function pointer from Windows thread...\n");
    uint64_t registers[32] = {0};
    registers[0] = 58; // Input register = 58

    JitFunction func = (JitFunction)exec_mem;
    func(registers);

    printf("[+] Execution Successful! Register X0 = %llu (Expected: 100)\n", (unsigned long long)registers[0]);

    // 4. Clean up
    VirtualFree(exec_mem, 0, MEM_RELEASE);
    printf("\n[+] Windows Native Client execution verified with zero stutter!\n");
    return 0;
}

